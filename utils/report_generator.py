
from pathlib import Path
from datetime import datetime
from html import escape


def generate_reports(target, results, output_dir="reports"):
    report_dir = Path(output_dir)
    report_dir.mkdir(parents=True, exist_ok=True)

    timestamp = datetime.now().astimezone().strftime(
        "%d %B %Y, %I:%M:%S %p %Z"
    )

    safe_target = "".join(
        char if char.isalnum() or char in ".-_" else "_"
        for char in target
    )

    html_path = report_dir / f"{safe_target}.html"
    txt_path = report_dir / f"{safe_target}.txt"

    # Convert collected results into readable text.
    def format_value(value):
        if isinstance(value, dict):
            return "\n".join(
                f"{key}: {format_value(item)}"
                for key, item in value.items()
            )

        if isinstance(value, (list, tuple, set)):
            return "\n".join(format_value(item) for item in value)

        if value is None:
            return "Not available"

        return str(value)

    # Generate TXT report.
    txt_lines = [
        "=" * 65,
        "SNIT RECONNAISSANCE FRAMEWORK",
        "=" * 65,
        f"Target: {target}",
        f"Generated: {timestamp}",
        ""
    ]

    for section, data in results.items():
        txt_lines.extend([
            "-" * 65,
            section.upper(),
            "-" * 65,
            format_value(data),
            ""
        ])

    txt_lines.append("=" * 65)
    txt_lines.append("END OF REPORT")

    txt_path.write_text(
        "\n".join(txt_lines),
        encoding="utf-8"
    )

    # Generate HTML report.
    sections = []

    for section, data in results.items():
        content = escape(format_value(data))

        sections.append(
            f"""
            <section>
                <h2>{escape(str(section))}</h2>
                <pre>{content}</pre>
            </section>
            """
        )

    html_content = f"""
    <!DOCTYPE html>
    <html lang="en">
    <head>
        <meta charset="UTF-8">
        <meta name="viewport" content="width=device-width, initial-scale=1">
        <title>SNIT Recon Report - {escape(target)}</title>
        <style>
            body {{
                font-family: Arial, sans-serif;
                background: #f4f6f9;
                color: #243447;
                margin: 0;
                padding: 30px;
            }}
            header {{
                background: #17365d;
                color: white;
                padding: 25px;
                border-radius: 8px;
            }}
            section {{
                background: white;
                padding: 20px;
                margin-top: 20px;
                border-radius: 8px;
                box-shadow: 0 2px 8px rgba(0,0,0,0.06);
            }}
            h2 {{
                color: #17365d;
                border-bottom: 2px solid #e5eaf0;
                padding-bottom: 10px;
            }}
            pre {{
                white-space: pre-wrap;
                overflow-wrap: anywhere;
                font-family: Consolas, monospace;
                line-height: 1.6;
            }}
            footer {{
                margin-top: 25px;
                color: #667085;
                font-size: 13px;
            }}
        </style>
    </head>
    <body>
        <header>
            <h1>SNIT Reconnaissance Framework</h1>
            <p>Target: {escape(target)}</p>
            <p>Generated: {escape(timestamp)}</p>
        </header>

        {''.join(sections)}

        <footer>
            Generated by SNIT Recon. For authorized security assessments only.
        </footer>
    </body>
    </html>
    """

    html_path.write_text(html_content, encoding="utf-8")

    print("\n[+] Reports generated successfully.")
    print(f"[+] HTML Report: {html_path}")
    print(f"[+] TXT Report: {txt_path}")

    return {
        "html": str(html_path),
        "txt": str(txt_path)
    }
